// Run against an isolated local preview: node tests/ui.cjs
// Requires Playwright as a development tool and Microsoft Edge, never in the app image.
const {chromium} = require('playwright');
const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const base = process.env.TEST_BASE_URL || 'http://localhost:8088';
const env = fs.existsSync(path.join(__dirname, '../.env')) ? fs.readFileSync(path.join(__dirname, '../.env'), 'utf8') : '';
const password = process.env.TEST_ADMIN_PASSWORD || env.match(/^JUSTOPEN_ADMIN_PASSWORD=(.*)$/m)?.[1].trim();
assert.ok(password, 'Set TEST_ADMIN_PASSWORD or a local .env password.');
const slug = 'check-' + Date.now();
const target = 'https://hoerbuch.warsowerk.de/?tag=existing&x=a%2Fb&x=two#chapter-2';
const artifacts = path.join(__dirname, '../artifacts');
fs.mkdirSync(artifacts, {recursive:true});

(async () => {
    const browser = await chromium.launch({headless:true, channel:process.env.TEST_BROWSER_CHANNEL || 'msedge'});
    try {
        const context = await browser.newContext({viewport:{width:1440,height:1080}});
        const page = await context.newPage();
        const errors = [];
        page.on('pageerror', e => errors.push(e.message));
        page.on('console', m => { if (m.type() === 'error' && /Content Security Policy|Refused to|Uncaught/.test(m.text())) errors.push(m.text()); });
        const health = await fetch(base + '/healthz'); assert.equal(health.status, 200);
        assert.deepEqual(await health.json(), {ok:true});
        for (const blocked of ['/smartlinks.php','/engine.php','/.env','/.htaccess','/captain-definition','/templates/smart-admin.php','/tests/ui.cjs','/data/test.sqlite','/.git/config']) {
            const r = await fetch(base + blocked); assert.ok([403,404].includes(r.status), 'Private file blocked: ' + blocked + ', got ' + r.status);
        }
        const missing = await fetch(base + '/l/missing-link'); assert.equal(missing.status, 404);
        const wrongMethod = await fetch(base + '/l/missing-link', {method:'POST'}); assert.equal(wrongMethod.status, 405);
        assert.equal((await fetch(base + '/admin/preview')).status,405);
        assert.equal((await fetch(base + '/social')).status,200);
        const legacy = await fetch(base + '/api/shorten', {method:'POST',body:new URLSearchParams({url:'https://www.youtube.com/watch?v=dQw4w9WgXcQ'})});
        assert.equal(legacy.status,200); assert.equal((await legacy.json()).provider,'yt');
        await page.goto(base + '/admin');
        await page.locator('#password').fill(password);
        await page.getByRole('button', {name:'Studio öffnen'}).click();
        await page.waitForURL(base + '/admin');
        await page.locator('#url').fill(target);
        await page.locator('#slug').fill(slug);
        await page.locator('#brand').fill('Warsowerk');
        await page.locator('#title').fill('Dein nächstes Hörbuch wartet.');
        await page.locator('#primary_label').fill('Hörbuch entdecken');
        await page.locator('#secondary_label').fill('Link kopieren');
        await page.locator('#secondary_action').selectOption('copy');
        await page.locator('.utm-details summary').click();
        await page.locator('#utm_source').fill('instagram');
        await page.locator('#utm_medium').fill('dm');
        await page.locator('#utm_campaign').fill('Hörbuch & mehr');
        assert.equal(await page.locator('#preview-title, #preview-description').count(),0);
        assert.equal(await page.locator('#preview-host').textContent(), 'hoerbuch.warsowerk.de');
        const popupPromise = page.waitForEvent('popup');
        await page.getByRole('button', {name:'Vorschau öffnen',exact:true}).click();
        const popup = await popupPromise; await popup.waitForLoadState();
        assert.equal(await popup.locator('body').getAttribute('data-preview'), 'true');
        await popup.locator('#open-external').click({force:true});
        assert.ok(popup.url().endsWith('/admin/preview'));
        await popup.close();
        await page.getByRole('button', {name:'Link erstellen',exact:true}).click();
        await page.waitForURL('**/admin?edit=' + slug + '&saved=1');
        assert.equal(await page.locator('#share-url').inputValue(), base + '/l/' + slug);
        assert.equal(await page.locator('#slug').getAttribute('readonly'), '');
        await page.screenshot({path:path.join(artifacts,'studio-desktop.png'),fullPage:true});
        const csrf = await page.locator('input[name=csrf]').first().inputValue();
        const invalidCsrf = await context.request.post(base + '/admin', {form:{action:'save',csrf:'invalid'}});
        assert.equal(invalidCsrf.status(),403);
        const oldCookie = (await context.cookies()).find(c => c.name === 'justopen_admin');
        assert.equal(oldCookie.httpOnly,true); assert.equal(oldCookie.sameSite,'Strict');
        const go = await fetch(base + '/go/' + slug + '?utm_content=dynamic&url=https://evil.test', {redirect:'manual'});
        assert.equal(go.status,302);
        const expected = 'https://hoerbuch.warsowerk.de/?tag=existing&x=a%2Fb&x=two&utm_source=instagram&utm_medium=dm&utm_campaign=H%C3%B6rbuch%20%26%20mehr&utm_content=dynamic#chapter-2';
        assert.equal(go.headers.get('location'),expected);
        assert.equal(go.headers.get('set-cookie'),null);
        const landing = await context.newPage();
        await landing.goto(base + '/l/' + slug + '?utm_content=dynamic');
        assert.equal(await landing.locator('.landing-actions > *').count(),2);
        assert.equal(await landing.locator('.description, .landing-footer').count(),0);
        assert.equal(await landing.locator('h1').getAttribute('class'),'sr-only');
        assert.equal(await landing.locator('.destination').textContent(),'hoerbuch.warsowerk.de');
        assert.equal(await landing.locator('#open-external').getAttribute('href'),expected);
        assert.equal(await landing.locator('#countdown-panel').isHidden(),true);
        const centered = () => {
            const button = document.getElementById('open-external');
            const label = button.firstElementChild;
            const b = button.getBoundingClientRect(), l = label.getBoundingClientRect();
            return Math.abs((b.left + b.right) / 2 - (l.left + l.right) / 2) < 1;
        };
        assert.ok(await landing.evaluate(centered), 'Primary label centered on desktop.');
        await landing.evaluate(() => Object.defineProperty(navigator,'clipboard',{value:undefined, configurable:true}));
        await landing.locator('#secondary').click();
        assert.equal(await landing.locator('#copy-fallback').isVisible(),true);
        assert.equal(await landing.locator('#copy-url').inputValue(),expected);
        await landing.setViewportSize({width:390,height:844});
        assert.ok(await landing.evaluate(centered), 'Primary label centered on mobile.');
        await landing.screenshot({path:path.join(artifacts,'landing-mobile.png'),fullPage:true});
        assert.ok(await landing.evaluate(() => document.documentElement.scrollWidth <= innerWidth), 'Landing has no mobile overflow.');
        await landing.close();

        const iosContext = await browser.newContext({userAgent:'Mozilla/5.0 (iPhone; CPU iPhone OS 18_0 like Mac OS X) Instagram 400',viewport:{width:390,height:844}});
        const ios = await iosContext.newPage(); await ios.goto(base + '/l/' + slug);
        assert.equal(await ios.locator('#open-external').getAttribute('href'), 'instagram://extbrowser/?url=' + encodeURIComponent(base + '/go/' + slug));
        assert.equal(await ios.locator('#browser-hint').isVisible(),false);
        await ios.locator('#open-external').evaluate(el=>el.addEventListener('click',e=>e.preventDefault()));
        await ios.locator('#open-external').click();
        assert.equal(await ios.locator('#browser-hint').isVisible(),true);
        await iosContext.close();
        const androidContext = await browser.newContext({userAgent:'Mozilla/5.0 (Linux; Android 15) Instagram 400'});
        const android = await androidContext.newPage(); await android.goto(base + '/l/' + slug);
        assert.ok((await android.locator('#open-external').getAttribute('href')).includes('package=com.android.chrome;'));
        assert.ok((await android.locator('#open-external').getAttribute('href')).includes(encodeURIComponent(base + '/l/' + slug)));
        await androidContext.close();
        const nojsContext = await browser.newContext({javaScriptEnabled:false});
        const nojs = await nojsContext.newPage(); await nojs.goto(base + '/l/' + slug);
        assert.ok((await nojs.locator('#open-external').getAttribute('href')).startsWith('https://hoerbuch.warsowerk.de/'));
        assert.equal(await nojs.locator('noscript').isVisible(),true);
        assert.equal(await nojs.locator('#copy-fallback').isVisible(),true);
        await nojsContext.close();
        await page.bringToFront();
        await page.locator('#delay').fill('2');
        await page.getByRole('button', {name:'Änderungen speichern'}).click();
        await page.waitForURL('**/admin?edit=' + slug + '&saved=1');
        const countdownPage = await context.newPage();
        await countdownPage.addInitScript(() => document.addEventListener('click', event => { if (event.target.closest('#open-external')) event.preventDefault(); }, true));
        await countdownPage.goto(base + '/l/' + slug); await countdownPage.bringToFront();
        await countdownPage.waitForFunction(() => document.getElementById('countdown').textContent === 'Automatisches Öffnen beendet.');
        await countdownPage.close();
        const cancelPage = await context.newPage(); await cancelPage.goto(base + '/l/' + slug);
        await cancelPage.locator('#cancel-countdown').check();
        assert.equal(await cancelPage.locator('#countdown').textContent(),'Automatisches Öffnen gestoppt.');
        await cancelPage.close();
        await page.bringToFront();
        await page.locator('#delay').fill('');
        await page.locator('input[name=active]').uncheck();
        await page.getByRole('button', {name:'Änderungen speichern'}).click();
        await page.waitForURL('**/admin?edit=' + slug + '&saved=1');
        assert.equal((await fetch(base + '/l/' + slug)).status,410);
        assert.equal((await fetch(base + '/go/' + slug,{redirect:'manual'})).status,410);
        await page.locator('input[name=active]').check();
        await page.getByRole('button', {name:'Änderungen speichern'}).click();
        await page.waitForURL('**/admin?edit=' + slug + '&saved=1');
        assert.equal((await fetch(base + '/l/' + slug)).status,200);
        // Defaults affect new links, not links already shared.
        await page.goto(base + '/admin?view=defaults');
        const oldDefaultTitle = await page.locator('#title').inputValue();
        const oldDefaultBrand = await page.locator('#brand').inputValue();
        await page.locator('#title').fill('Neue Vorlage für meine Links');
        await page.locator('#brand').fill('Aktuelle Vorlage');
        await page.getByRole('button',{name:'Vorlage speichern'}).click();
        await page.waitForURL('**/admin?view=defaults&saved=1');
        await page.goto(base + '/admin');
        assert.equal(await page.locator('#title').inputValue(),'Neue Vorlage für meine Links');
        await page.goto(base + '/admin?edit=' + slug);
        assert.equal(await page.locator('#title').inputValue(),'Dein nächstes Hörbuch wartet.');
        assert.equal(await page.locator('#brand').inputValue(),'Warsowerk');
        await page.getByRole('button', {name:'Vorlage anwenden', exact:true}).click();
        await page.waitForURL(base + '/admin');
        assert.equal(await page.locator('#brand').inputValue(),'Aktuelle Vorlage');
        assert.equal(await page.locator('#preview-brand').textContent(),'Aktuelle Vorlage');
        assert.equal(await page.locator('#title').inputValue(),'Dein nächstes Hörbuch wartet.');
        assert.equal(await page.locator('#url').inputValue(),target);
        assert.equal(await page.locator('#slug').inputValue(),slug);
        assert.equal(await page.locator('#utm_source').inputValue(),'instagram');
        assert.equal(await page.locator('#utm_campaign').inputValue(),'Hörbuch & mehr');
        assert.equal(await page.locator('input[name=forward_utm]').isChecked(),true);
        assert.equal(await page.locator('input[name=active]').isChecked(),true);
        assert.match(await (await fetch(base + '/l/' + slug)).text(),/>Warsowerk<\/span>/, 'Applying alone does not persist.');
        await page.getByRole('button', {name:'Änderungen speichern'}).click();
        await page.waitForURL('**/admin?edit=' + slug + '&saved=1');
        assert.match(await (await fetch(base + '/l/' + slug)).text(),/>Aktuelle Vorlage<\/span>/);
        await page.locator('#secondary_action').selectOption('custom');
        await page.locator('#secondary_url').fill('https://warsowerk.de/kontakt');
        await page.locator('#shape').selectOption('square');
        await page.locator('#accent').fill('#283b50');
        await page.getByRole('button', {name:'Änderungen speichern'}).click();
        await page.waitForURL('**/admin?edit=' + slug + '&saved=1');
        const customized = await context.newPage(); await customized.goto(base + '/l/' + slug);
        assert.equal(await customized.locator('#secondary').getAttribute('href'),'https://warsowerk.de/kontakt');
        assert.equal(await customized.locator('#open-external').evaluate(el=>getComputedStyle(el).borderRadius),'4px');
        assert.equal(await customized.locator('#open-external').evaluate(el=>getComputedStyle(el).backgroundColor),'rgb(40, 59, 80)');
        await customized.close();
        await page.goto(base + '/admin?view=defaults');
        await page.locator('#title').fill(oldDefaultTitle);
        await page.locator('#brand').fill(oldDefaultBrand);
        await page.getByRole('button',{name:'Vorlage speichern'}).click();
        await page.waitForURL('**/admin?view=defaults&saved=1');
        await page.goto(base + '/admin?edit=' + slug);
        await page.setViewportSize({width:390,height:844});
        assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), 'Admin has no mobile overflow.');
        await page.screenshot({path:path.join(artifacts,'studio-mobile.png'),fullPage:true});
        assert.equal(errors.length,0,errors.join('\n'));
        await page.getByRole('button', {name:'Abmelden'}).click();
        await page.waitForURL(base + '/admin');
        assert.equal(await page.locator('#password').isVisible(),true);
        const afterLogout = await context.request.post(base + '/admin',{form:{action:'save',csrf}});
        assert.equal(afterLogout.status(),403);
        await context.close();
        console.log('HTTP and browser flow passed: auth, CSRF, privacy, create/edit, preview, UTM, mobile layouts, iOS/Android hrefs, no-JS, countdown, cancellation, deactivate/reactivate, logout.');
        console.log('Artifacts: ' + artifacts);
    } finally { await browser.close(); }
})().catch(e => { console.error(e); process.exitCode=1; });
