const assert = require('node:assert/strict');
const {environment, externalHref} = require('../assets/landing.js');
const target = 'https://hoerbuch.warsowerk.de/?utm_source=instagram#chapter';
const handoff = 'https://go.example.com/go/hoerbuch?utm_medium=dm%20%26%20more';
const fallback = 'https://go.example.com/l/hoerbuch?utm_medium=dm%20%26%20more';
const android = environment('Mozilla/5.0 (Linux; Android 15) Instagram 400');
assert.equal(android.android, true);
assert.equal(android.inApp, true);
const intent = externalHref(target, handoff, fallback, android);
assert.ok(intent.startsWith('intent://go.example.com/go/hoerbuch?utm_medium=dm%20%26%20more#Intent;scheme=https;'));
assert.ok(intent.includes('package=com.android.chrome;'));
assert.ok(intent.includes('S.browser_fallback_url=' + encodeURIComponent(fallback)));
assert.ok(!intent.includes('#chapter'));
const ios = environment('Mozilla/5.0 (iPhone; CPU iPhone OS 18_0) Instagram 400');
assert.equal(externalHref(target, handoff, fallback, ios), 'instagram://extbrowser/?url=' + encodeURIComponent(handoff));
const facebook = environment('Mozilla/5.0 (iPhone; CPU iPhone OS 18_0) FBAN/FBIOS FBAV/500');
assert.equal(facebook.manual, true);
assert.equal(externalHref(target, handoff, fallback, facebook), target);
const safari = environment('Mozilla/5.0 (iPhone; CPU iPhone OS 18_0) Safari/604.1');
assert.equal(safari.inApp, false);
assert.equal(externalHref(target, handoff, fallback, safari), target);
assert.equal(environment('Mozilla/5.0 (Macintosh)', true).ios, true);
assert.equal(environment('Mozilla/5.0 (Linux; Android 15; wv)').inApp, true);
const desktop = environment('Mozilla/5.0 (Windows NT 10.0) Chrome/140.0');
assert.equal(externalHref(target, handoff, fallback, desktop), target);
const threads = environment('Mozilla/5.0 (iPhone) Barcelona');
assert.equal(externalHref(target, handoff, fallback, threads), 'barcelona://extbrowser/?url=' + encodeURIComponent(handoff));
console.log('Browser handoff checks passed.');
